#!/usr/bin/env python3

import pathlib
import sys

from fontTools.ttLib.standardGlyphOrder import standardGlyphOrder as MAC_NAMES
from fontTools.cffLib import cffStandardStrings as CFF_STRINGS

OUT = pathlib.Path(__file__).resolve().parents[3] / "src" / "daecore" / "src" / "daetype" / "glyph_names" / "tables.rs"

def table(name, doc, values):
    lines = [doc, f"pub(crate) const {name}: [&str; {len(values)}] = ["]
    row = "   "
    for v in values:
        lit = f' "{v}",'
        if len(row) + len(lit) > 99:
            lines.append(row)
            row = "   "
        row += lit
    lines.append(row)
    lines.append("];")
    return "\n".join(lines)

def main():
    if len(MAC_NAMES) != 258 or len(CFF_STRINGS) != 391:
        sys.exit(f"unexpected table sizes: {len(MAC_NAMES)} mac, {len(CFF_STRINGS)} cff")
    if any('"' in n or "\\" in n for n in list(MAC_NAMES) + list(CFF_STRINGS)):
        sys.exit("a name needs escaping, which this generator does not do")

    body = "\n\n".join([
        "// Generated by scripts/tools/gen/glyph-name-tables.py. Do not edit.",
        table(
            "MACINTOSH_NAMES",
            "// A `post` 2.0 name index below 258 names one of these directly.",
            MAC_NAMES,
        ),
        table(
            "CFF_STANDARD_STRINGS",
            "// A SID below 391 names one of these; at or above it, the font's String INDEX at sid - 391.",
            CFF_STRINGS,
        ),
    ])
    OUT.write_text(body + "\n")
    print(f"wrote {OUT}: {len(MAC_NAMES)} Macintosh names, {len(CFF_STRINGS)} CFF standard strings")

if __name__ == "__main__":
    main()
