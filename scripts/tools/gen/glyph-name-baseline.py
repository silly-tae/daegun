#!/usr/bin/env python3
import glob, sys
from fontTools.ttLib import TTFont

print("# font\tgid\tname   (generated by scripts/tools/gen/glyph-name-baseline.py)")
print("# a font listed with no rows names nothing: post 3.0 and no CFF charset")
for p in sorted(glob.glob("assets/test-fonts/*/*.ttf") + glob.glob("assets/test-fonts/*/*.otf")):
    try:
        f = TTFont(p, lazy=True)
    except Exception:
        continue
    named = ("post" in f and f["post"].formatType == 2.0) or "CFF " in f
    print(f"@ {p}\t{'named' if named else 'unnamed'}")
    if not named:
        continue
    order = f.getGlyphOrder()
    n = len(order)
    picks = {0, 1, 2, 256, 257, 258, 259, n - 2, n - 1} | {n * k // 11 for k in range(1, 11)}
    for g in sorted(i for i in picks if 0 <= i < n):
        print(f"{p}\t{g}\t{order[g]}")
